#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { assertInside, detectLanguages, lexists, loadLanguages, resolveDest, walk } from './devops-setup.mjs'

const BUILD_MODE = { 'python': 'none', 'javascript-typescript': 'none', 'ruby': 'none', 'rust': 'none', 'actions': 'none', 'csharp': 'none', 'java-kotlin': 'none', 'cpp': 'autobuild', 'go': 'autobuild', 'swift': 'autobuild' }

// A pattern starting with "*" matches a file-name suffix.
const ECOSYSTEMS = [
  ['npm', ['package.json']], ['cargo', ['Cargo.toml']], ['nuget', ['*.csproj', '*.fsproj']],
  ['pip', ['requirements.txt', 'pyproject.toml', 'Pipfile']], ['gomod', ['go.mod']], ['maven', ['pom.xml']],
  ['gradle', ['build.gradle', 'build.gradle.kts']], ['composer', ['composer.json']], ['bundler', ['Gemfile']],
  ['pub', ['pubspec.yaml']], ['mix', ['mix.exs']], ['swift', ['Package.swift']], ['terraform', ['*.tf']],
  ['docker', ['Dockerfile']], ['docker-compose', ['docker-compose.yml', 'docker-compose.yaml', 'compose.yaml']],
]

const nameMatches = (pattern, name) => (pattern.startsWith('*') ? name.endsWith(pattern.slice(1)) : name === pattern)

function ecosystemsIn(files, hasWorkflows) {
  const found = []
  for (const [ecosystem, manifests] of ECOSYSTEMS) {
    const dirs = new Set()
    for (const rel of files) if (manifests.some(m => nameMatches(m, rel.split('/').pop()))) dirs.add(path.posix.dirname(rel) === '.' ? '/' : '/' + path.posix.dirname(rel))
    if (dirs.size > 0) found.push({ ecosystem, directories: [...dirs].sort().slice(0, 8) })
  }
  if (hasWorkflows) found.push({ ecosystem: 'github-actions', directories: ['/'] })
  return found
}

function codeqlWorkflow(languages, branch) {
  const rows = languages.map(language => `          - language: ${language}\n            build-mode: ${BUILD_MODE[language] ?? 'none'}\n            runner: ${language === 'swift' ? 'macos-latest' : 'ubuntu-latest'}`).join('\n')
  return `# Use this workflow or GitHub's default setup for code scanning, not both.
# Pin the actions to full commit SHAs.
name: CodeQL

on:
  push:
    branches: ["${branch}"]
  pull_request:
    branches: ["${branch}"]
  schedule:
    - cron: "17 4 * * 1"

permissions:
  contents: read

jobs:
  analyze:
    name: Analyze (\${{ matrix.language }})
    runs-on: \${{ matrix.runner }}
    permissions:
      security-events: write
      packages: read
      actions: read
      contents: read
    strategy:
      fail-fast: false
      matrix:
        include:
${rows}
    steps:
      - name: Check out the code
        uses: actions/checkout@v4

      - name: Initialize CodeQL
        uses: github/codeql-action/init@v3
        with:
          languages: \${{ matrix.language }}
          build-mode: \${{ matrix.build-mode }}
          queries: security-and-quality

      - name: Analyze
        uses: github/codeql-action/analyze@v3
        with:
          category: "/language:\${{ matrix.language }}"
`
}

const DEPENDENCY_REVIEW = `# Needs the dependency graph, which is on by default for public repositories.
name: Dependency review

on:
  pull_request:

permissions:
  contents: read

jobs:
  dependency-review:
    name: Dependency review
    runs-on: ubuntu-latest
    steps:
      - name: Check out the code
        uses: actions/checkout@v4

      - name: Review dependency changes
        uses: actions/dependency-review-action@v4
        with:
          fail-on-severity: high
`

function dependabot(ecosystems) {
  const entries = ecosystems.flatMap(({ ecosystem, directories }) => directories.map(directory => `  - package-ecosystem: "${ecosystem}"
    directory: "${directory}"
    schedule:
      interval: "weekly"
    open-pull-requests-limit: 5
    groups:
      ${ecosystem}-minor-and-patch:
        patterns: ["*"]
        update-types: ["minor", "patch"]`))
  return `version: 2\nupdates:\n${entries.join('\n')}\n`
}

const SECURITY_MD = `# Security policy

## Reporting a vulnerability

Please do not open a public issue for a security problem. Use GitHub's
private vulnerability reporting (the "Report a vulnerability" button on the
Security tab) or write to <SECURITY CONTACT: fill in an address>.

Include what you found, how to reproduce it, and the version affected. We
aim to acknowledge a report within <fill in: for example 3 working days>.

## Supported versions

<Fill in which versions receive security fixes.>
`

function remote(dest) {
  try {
    const config = fs.readFileSync(path.join(dest, '.git', 'config'), 'utf8')
    const m = /url\s*=\s*(?:https:\/\/github\.com\/|git@github\.com:)([\w.-]+)\/([\w.-]+?)(?:\.git)?\s*$/m.exec(config)
    return m ? { owner: m[1], repo: m[2] } : undefined
  } catch {
    return undefined
  }
}

function commandsDoc(r, branch, languages, checks) {
  const slug = r ? `${r.owner}/${r.repo}` : '<OWNER>/<REPO>'
  return `# GitHub Advanced Security: repository settings (run by a human)

Generated by devops-multi-agent-team for ${slug}. Nothing here has been run.
These change the repository's settings and need an admin token (\`gh auth login\`),
so a seat never runs them. Private repositories need the GitHub Code Security /
Secret Protection plans for some of them. Check each one before running it.

## Alerts and updates

\`\`\`bash
gh api -X PUT repos/${slug}/vulnerability-alerts                 # Dependabot alerts
gh api -X PUT repos/${slug}/automated-security-fixes             # Dependabot security updates
gh api -X PUT repos/${slug}/private-vulnerability-reporting      # private vulnerability reporting
\`\`\`

## Secret scanning and push protection

\`\`\`bash
gh api -X PATCH repos/${slug} --input - <<'JSON'
{ "security_and_analysis": {
    "secret_scanning": { "status": "enabled" },
    "secret_scanning_push_protection": { "status": "enabled" } } }
JSON
\`\`\`

## Code scanning: choose ONE

1. The workflow file \`.github/workflows/codeql.yml\` (generated; reviewable in git). Nothing else to do.
2. GitHub's default setup (do not also use the workflow):

\`\`\`bash
gh api -X PATCH repos/${slug}/code-scanning/default-setup --input - <<'JSON'
{ "state": "configured", "query_suite": "extended", "languages": ${JSON.stringify(languages)} }
JSON
\`\`\`

## Branch ruleset (review \`.devops/ghas/ruleset.json\` first)

The required check names are ${checks.map(c => `\`${c}\``).join(', ')}. A job's check name
must match its workflow's job \`name\`.

\`\`\`bash
gh api -X POST repos/${slug}/rulesets --input .devops/ghas/ruleset.json
\`\`\`

## Verify

\`\`\`bash
gh api repos/${slug} --jq '.security_and_analysis'
gh api repos/${slug}/code-scanning/default-setup
\`\`\`
`
}

function ruleset(checks) {
  return JSON.stringify({
    name: 'default branch protection (devops-multi-agent-team template)',
    target: 'branch',
    enforcement: 'active',
    conditions: { ref_name: { include: ['~DEFAULT_BRANCH'], exclude: [] } },
    rules: [
      { type: 'deletion' },
      { type: 'non_fast_forward' },
      { type: 'pull_request', parameters: { required_approving_review_count: 1, dismiss_stale_reviews_on_push: true, require_code_owner_review: false, require_last_push_approval: false, required_review_thread_resolution: true } },
      { type: 'required_status_checks', parameters: { strict_required_status_checks_policy: true, required_status_checks: checks.map(context => ({ context })) } },
    ],
  }, null, 2) + '\n'
}

export function ghasPlan(destInput, { branch = 'main', apply = false, force = false, roots } = {}) {
  const dest = resolveDest(destInput, roots)
  if (!/^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$/.test(branch)) throw new Error('branch must be a plain branch name')
  const config = loadLanguages(dest)
  const found = walk(dest)
  const detected = detectLanguages(dest, config, found).map(d => d.id)
  const codeql = [...new Set(config.languages.filter(l => detected.includes(l.id) && l.security?.sast?.tool === 'codeql').map(l => l.security.sast.language))].sort()
  const hasWorkflows = found.dirs.includes('.github/workflows') || found.files.some(f => f.startsWith('.github/workflows/'))
  if (hasWorkflows && !codeql.includes('actions')) codeql.push('actions')
  const ecosystems = ecosystemsIn(found.files, hasWorkflows)
  const warnings = []
  const checks = ['Dependency review', ...codeql.map(language => `Analyze (${language})`)]
  const files = []
  if (codeql.length > 0) files.push(['.github/workflows/codeql.yml', codeqlWorkflow(codeql, branch)])
  else warnings.push('no language CodeQL supports was detected, so no CodeQL workflow was planned')
  files.push(['.github/workflows/dependency-review.yml', DEPENDENCY_REVIEW])
  if (ecosystems.length > 0) files.push(['.github/dependabot.yml', dependabot(ecosystems)])
  else warnings.push('no package manifest was detected, so no Dependabot file was planned')
  if (!found.files.some(f => /^(\.github\/)?SECURITY\.md$/i.test(f)) && !lexists(path.join(dest, 'SECURITY.md'))) files.push(['SECURITY.md', SECURITY_MD])
  files.push(['.devops/ghas/commands.md', commandsDoc(remote(dest), branch, codeql, checks)])
  files.push(['.devops/ghas/ruleset.json', ruleset(checks)])
  warnings.push('workflow actions are referenced by tag; pin them to full commit SHAs before relying on them')
  if (branch === 'main') warnings.push('assumed the default branch is "main"; pass branch if it is not')

  const plan = files.map(([rel, text]) => {
    const target = path.join(dest, rel)
    const exists = lexists(target)
    const same = exists && fs.readFileSync(target, 'utf8') === text
    const action = same ? 'same' : exists && !force ? 'kept' : exists ? 'replace' : 'create'
    if (apply && (action === 'create' || action === 'replace')) {
      assertInside(dest, target)
      fs.mkdirSync(path.dirname(target), { recursive: true })
      fs.writeFileSync(target, text)
    }
    return { path: rel, action: apply && action !== 'same' && action !== 'kept' ? (action === 'create' ? 'created' : 'replaced') : action }
  })
  return { dest, applied: apply, codeqlLanguages: codeql, ecosystems, requiredChecks: checks, files: plan, warnings, humanOnly: 'Repository settings are printed in .devops/ghas/commands.md for a human to run; nothing was changed on GitHub.' }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2)
  argv.shift()
  const opt = name => { const i = argv.indexOf(name); return i === -1 ? undefined : argv[i + 1] }
  try {
    console.log(JSON.stringify(ghasPlan(opt('--dest') ? path.resolve(opt('--dest')) : process.cwd(), { branch: opt('--branch') ?? 'main', apply: argv.includes('--apply'), force: argv.includes('--force') }), null, 2))
  } catch (error) {
    console.error(`devops-ghas: ${error.message}`)
    process.exitCode = 1
  }
}
